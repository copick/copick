"""Validate stored CETS objects against the vendored JSON Schemas of the targeted CETS data-model version.

The schemas are generated by ``tests/scripts/generate_cets_schemas.py`` into ``tests/data/cets/<commit>/``.
"""

import json
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict

from copick.util.cets import CETS_TARGET

SCHEMA_ROOT = Path(__file__).parent / "data" / "cets"


@lru_cache(maxsize=None)
def cets_schema(model: str, commit: str = CETS_TARGET["commit"]) -> Dict[str, Any]:
    """The JSON Schema of CETS model ``model`` at ``commit``."""
    return json.loads((SCHEMA_ROOT / commit / f"{model}.schema.json").read_text())


def validate_cets(instance: Dict[str, Any], model: str) -> None:
    """Raise ``jsonschema.ValidationError`` unless ``instance`` is a valid serialized CETS ``model``."""
    import jsonschema

    jsonschema.Draft202012Validator(cets_schema(model)).validate(instance)


def validate_tilt_series_block(block: Dict[str, Any]) -> None:
    """Validate the CETS objects of a stored tilt series block."""
    validate_cets(block["tilt_series"], "TiltSeries")
    validate_cets(block["acquisition_session"], "AcquisitionSession")
    validate_cets(block["instrument"], "Instrument")
